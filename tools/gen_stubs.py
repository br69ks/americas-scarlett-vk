#!/usr/bin/env python3
"""Generate placeholder IAT stubs and a DLL-qualified lookup registry.

These stubs are diagnostic fallbacks only: they intentionally do not claim to
implement the imported Windows/GDK API or its real function signature.
"""

import hashlib
import re
import sys
from collections import defaultdict
from pathlib import Path


_GENERATED_MARKER = "// AUTO-GENERATED BY tools/gen_stubs.py"
_ZIG_KEYWORDS = {
    "align", "allowzero", "and", "anyframe", "anytype", "asm", "async",
    "await", "break", "callconv", "catch", "comptime", "const", "continue",
    "defer", "else", "enum", "errdefer", "error", "export", "extern", "fn",
    "for", "if", "inline", "noalias", "noinline", "nosuspend", "opaque", "or",
    "orelse", "packed", "pub", "resume", "return", "linksection", "struct",
    "suspend", "switch", "test", "threadlocal", "try", "union", "unreachable",
    "usingnamespace", "var", "volatile", "while",
}


def _parse_decimal_or_prefixed_int(value: str) -> int | None:
    """Parse objdump's decimal ordinal, while tolerating an explicit 0x prefix."""
    try:
        return int(value, 0) if value.lower().startswith("0x") else int(value, 10)
    except ValueError:
        return None


def parse_imports(text: str) -> dict[str, list[tuple[str, int | None]]]:
    """Parse GNU ``objdump -p`` and LLVM ``llvm-readobj --coff-imports`` output.

    GNU objdump import rows use: VMA, Ordinal, Hint, Member-Name, Bound-To.
    For a named import the member name is column four; the hint is not an
    ordinal. LLVM's ``Symbol: name (hint)`` likewise contains a hint, while an
    empty symbol with a parenthesized number represents an ordinal import.

    The returned mapping is ``dll -> [(symbol_or_Ordinal_N, ordinal_or_none)]``.
    """
    imports: dict[str, list[tuple[str, int | None]]] = defaultdict(list)
    current_dll: str | None = None

    llvm_dll_re = re.compile(r"^\s*Name:\s*(\S+\.dll)\s*$", re.IGNORECASE)
    llvm_sym_re = re.compile(r"^\s*Symbol:\s*(.*?)\s*\((\d+)\)\s*$")
    hex_vma_re = re.compile(r"^[0-9a-fA-F]+$")

    for line in text.splitlines():
        stripped = line.strip()
        if not stripped:
            continue

        if stripped.lower().startswith("dll name:"):
            _, _, dll_part = stripped.partition(":")
            current_dll = dll_part.strip().lower()
            continue

        if match := llvm_dll_re.match(line):
            current_dll = match.group(1).lower()
            continue

        if stripped.startswith((
            "The Export Tables",
            "The Exception Directory",
            "The Function Table",
            "The Attribute Certificate Table",
            "The Base Relocation",
            "The TLS Directory",
            "The Load Configuration",
            "The Debug Directory",
            "The Resource Directory",
            "PE File Base Relocations",
            "Dump of ",
            "Sections:",
        )):
            current_dll = None
            continue

        if not current_dll:
            continue

        if match := llvm_sym_re.match(line):
            symbol = match.group(1).strip()
            value = int(match.group(2), 10)
            if symbol:
                imports[current_dll].append((symbol, None))
            elif 0 <= value <= 0xFFFF:
                imports[current_dll].append((f"Ordinal_{value}", value))
            else:
                raise ValueError(f"LLVM import ordinal is outside u16 range: {value}")
            continue

        parts = stripped.split()
        if not parts or not hex_vma_re.fullmatch(parts[0]):
            continue

        # Ignore bound-import address-table rows. These contain only numeric
        # fields and are not symbol or ordinal import records.
        if len(parts) >= 6 and all(
            hex_vma_re.fullmatch(token) for token in parts
        ):
            continue

        # Ignore the terminating zero-filled descriptor row.
        if len(parts) >= 5 and all(re.fullmatch(r"0+", token) for token in parts[1:]):
            continue

        # Current GNU objdump: VMA Ordinal Hint Member-Name [Bound-To].
        if len(parts) >= 4:
            ordinal_token = parts[1]
            member_name = parts[3]
            if ordinal_token.lower() != "<none>":
                ordinal = _parse_decimal_or_prefixed_int(ordinal_token)
                if ordinal is not None and 0 <= ordinal <= 0xFFFF:
                    imports[current_dll].append((f"Ordinal_{ordinal}", ordinal))
                elif ordinal is not None:
                    raise ValueError(f"objdump import ordinal is outside u16 range: {ordinal}")
                continue

            if member_name.lower() != "<none>":
                imports[current_dll].append((member_name, None))
            continue

        # Compatibility with the compact three-column format accepted by the
        # previous generator: VMA, hint/ordinal, symbol/<none>.
        if len(parts) >= 3:
            value_token, name = parts[1], parts[2]
            if name.lower() == "<none>":
                try:
                    ordinal = int(value_token, 16)
                except ValueError:
                    ordinal = _parse_decimal_or_prefixed_int(value_token)
                if ordinal is not None and 0 <= ordinal <= 0xFFFF:
                    imports[current_dll].append((f"Ordinal_{ordinal}", ordinal))
                elif ordinal is not None:
                    raise ValueError(f"compact import ordinal is outside u16 range: {ordinal}")
            elif name.lower() not in ("bound-to", "member-name"):
                imports[current_dll].append((name, None))

    # Deduplicate without changing import order.
    for dll, entries in imports.items():
        imports[dll] = list(dict.fromkeys(entries))

    return dict(imports)


def sanitize_zig_ident(name: str) -> str:
    """Convert a DLL/export name into a non-empty Zig identifier fragment."""
    clean = re.sub(r"[^a-zA-Z0-9_]", "_", name)
    if not clean:
        return "_unnamed"
    if clean[0].isdigit():
        clean = "_" + clean
    return clean


def zig_string_literal(value: str) -> str:
    """Return a Zig string literal with quotes, slashes, and controls escaped."""
    escaped: list[str] = []
    for char in value:
        codepoint = ord(char)
        if char == "\\":
            escaped.append("\\\\")
        elif char == '"':
            escaped.append('\\"')
        elif char == "\n":
            escaped.append("\\n")
        elif char == "\r":
            escaped.append("\\r")
        elif char == "\t":
            escaped.append("\\t")
        elif codepoint < 0x20 or codepoint == 0x7F:
            escaped.append(f"\\x{codepoint:02x}")
        else:
            escaped.append(char)
    return '"' + "".join(escaped) + '"'


def _module_identifier(dll: str, used: dict[str, str]) -> str:
    base = sanitize_zig_ident(dll.removesuffix(".dll").lower())
    if base in _ZIG_KEYWORDS:
        base = "_" + base

    owner = used.get(base)
    if owner is not None and owner != dll:
        digest = hashlib.sha256(dll.encode("utf-8")).hexdigest()[:8]
        candidate = f"{base}_{digest}"
        suffix = 2
        while candidate in used and used[candidate] != dll:
            candidate = f"{base}_{digest}_{suffix}"
            suffix += 1
        base = candidate

    used[base] = dll
    return base


def _remove_stale_generated_files(out_dir: Path, expected: set[str]) -> None:
    """Remove only obsolete files carrying this generator's own marker."""
    for path in out_dir.glob("*.zig"):
        if path.name in expected:
            continue
        try:
            with path.open("r", encoding="utf-8") as generated_file:
                first_line = generated_file.readline().rstrip("\r\n")
        except (OSError, UnicodeError):
            continue
        if first_line.startswith(_GENERATED_MARKER):
            path.unlink()


def generate_zig_files(
    imports: dict[str, list[tuple[str, int | None]]], out_dir: Path
) -> None:
    out_dir.mkdir(parents=True, exist_ok=True)
    registry_entries: list[str] = []
    module_imports: list[str] = []
    expected_files = {"registry.zig"}
    used_modules: dict[str, str] = {}

    for dll, funcs in sorted(imports.items(), key=lambda item: item[0].lower()):
        mod_base = _module_identifier(dll, used_modules)
        zig_filename = f"{mod_base}.zig"
        expected_files.add(zig_filename)
        zig_file = out_dir / zig_filename
        seen_fn_names: dict[str, int] = {}

        lines = [
            f"{_GENERATED_MARKER} — DO NOT EDIT MANUALLY",
            'const std = @import("std");',
            "",
        ]

        for original_name, ordinal in funcs:
            base_fn = f"stub_{sanitize_zig_ident(original_name)}"
            count = seen_fn_names.get(base_fn, 0)
            seen_fn_names[base_fn] = count + 1
            zig_fn = base_fn if count == 0 else f"{base_fn}_{count}"
            ordinal_text = str(ordinal) if ordinal is not None else "null"
            dll_literal = zig_string_literal(dll)
            name_literal = zig_string_literal(original_name)

            lines.extend([
                f"pub fn {zig_fn}() callconv(.{{ .x86_64_win = .{{}} }}) usize {{",
                f'    std.log.warn("[STUB] {{s}}!{{s}} (ord={{s}})", .{{ {dll_literal}, {name_literal}, {zig_string_literal(ordinal_text)} }});',
                "    return 0;",
                "}",
                "",
            ])

            registry_entries.append(
                "    .{ .dll = "
                + dll_literal
                + ", .name = "
                + name_literal
                + f", .ordinal = {ordinal_text}, .ptr = @ptrCast(&{mod_base}.{zig_fn}) }},"
            )

        zig_file.write_text("\n".join(lines) + "\n", encoding="utf-8")
        module_imports.append(
            f"pub const {mod_base} = @import({zig_string_literal(zig_filename)});"
        )

    registry_lines = [
        f"{_GENERATED_MARKER} — CENTRAL IAT STUB REGISTRY; DO NOT EDIT",
        'const std = @import("std");',
        "",
        *module_imports,
        "",
        "pub const StubEntry = struct {",
        "    dll: []const u8,",
        "    name: []const u8,",
        "    ordinal: ?u16,",
        "    ptr: *const anyopaque,",
        "};",
        "",
        "pub const all_stubs = [_]StubEntry{",
        *registry_entries,
        "};",
        "",
        "pub fn resolve(dll_name: []const u8, func_name: ?[]const u8, ordinal: ?u16) ?usize {",
        "    for (all_stubs) |entry| {",
        "        if (!std.ascii.eqlIgnoreCase(entry.dll, dll_name)) continue;",
        "        if (func_name) |fname| {",
        "            if (std.mem.eql(u8, entry.name, fname)) return @intFromPtr(entry.ptr);",
        "        }",
        "        if (ordinal != null and entry.ordinal != null and entry.ordinal.? == ordinal.?) {",
        "            return @intFromPtr(entry.ptr);",
        "        }",
        "    }",
        "    return null;",
        "}",
        "",
    ]
    (out_dir / "registry.zig").write_text("\n".join(registry_lines), encoding="utf-8")

    _remove_stale_generated_files(out_dir, expected_files)


def main() -> None:
    if len(sys.argv) < 2:
        print("Usage: python3 tools/gen_stubs.py <imports.txt> [output_dir]")
        sys.exit(1)

    imports_path = Path(sys.argv[1])
    out_dir = Path(sys.argv[2]) if len(sys.argv) > 2 else Path("src/shims/generated")

    raw_text = imports_path.read_text(encoding="utf-8", errors="replace")
    parsed = parse_imports(raw_text)
    if not parsed:
        print("Error: No DLL imports found. Check that imports.txt came from `objdump -p` or `llvm-readobj --coff-imports`.")
        sys.exit(1)

    generate_zig_files(parsed, out_dir)

    total_funcs = sum(len(functions) for functions in parsed.values())
    named_count = sum(
        1 for functions in parsed.values() for _, ordinal in functions if ordinal is None
    )
    ordinal_count = total_funcs - named_count
    print(
        f"Generated {len(parsed)} DLL shim modules ({total_funcs} entries: "
        f"{named_count} named, {ordinal_count} ordinal) in {out_dir}/"
    )
    for dll, funcs in sorted(parsed.items()):
        print(f"  - {dll}: {len(funcs)} functions")


if __name__ == "__main__":
    main()
